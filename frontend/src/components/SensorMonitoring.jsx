import React, { useState, useEffect, useCallback } from 'react';

export default function SensorMonitoring() {
  const apiBase = import.meta.env.VITE_API_BASE || 'http://127.0.0.1:8000';

  // State management
  const [latestReading, setLatestReading] = useState(null);
  const [historyReadings, setHistoryReadings] = useState([]);
  const [isLoading, setIsLoading] = useState(true);
  const [isGenerating, setIsGenerating] = useState(false);
  const [errorMessage, setErrorMessage] = useState(null);
  const [successMessage, setSuccessMessage] = useState(null);

  // Helper to format ISO 8601 strings into user-friendly local date/time
  const formatTimestamp = (isoString) => {
    if (!isoString) return 'N/A';
    try {
      const date = new Date(isoString);
      return date.toLocaleString();
    } catch {
      return isoString;
    }
  };

  // Fetch both latest reading and historical readings from actual backend endpoints
  const fetchSensorData = useCallback(async () => {
    setIsLoading(true);
    setErrorMessage(null);

    try {
      // 1. Fetch latest reading
      const latestPromise = fetch(`${apiBase}/api/sensors/latest`, {
        headers: { 'Accept': 'application/json' },
      });

      // 2. Fetch history records (newest 25)
      const historyPromise = fetch(`${apiBase}/api/sensors/readings?limit=25`, {
        headers: { 'Accept': 'application/json' },
      });

      const [latestRes, historyRes] = await Promise.all([latestPromise, historyPromise]);

      if (!latestRes.ok) {
        throw new Error(`Failed to load latest reading (HTTP ${latestRes.status})`);
      }
      if (!historyRes.ok) {
        throw new Error(`Failed to load reading history (HTTP ${historyRes.status})`);
      }

      const latestData = await latestRes.json();
      const historyData = await historyRes.json();

      setLatestReading(latestData.reading || null);
      setHistoryReadings(historyData.readings || []);
    } catch (err) {
      setErrorMessage(err.message || 'Error communicating with sensor API.');
    } finally {
      setIsLoading(false);
    }
  }, [apiBase]);

  // Initial fetch on component mount
  useEffect(() => {
    fetchSensorData();
  }, [fetchSensorData]);

  // Trigger POST /api/demo/generate-reading to create and persist ONE simulated reading
  const handleGenerateReading = async () => {
    setIsGenerating(true);
    setErrorMessage(null);
    setSuccessMessage(null);

    try {
      const response = await fetch(`${apiBase}/api/demo/generate-reading`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Accept': 'application/json',
        },
        body: JSON.stringify({}), // Empty payload triggers realistic algorithmic simulation
      });

      if (!response.ok) {
        const errorData = await response.json().catch(() => ({}));
        throw new Error(errorData.detail || `Server error (HTTP ${response.status})`);
      }

      const data = await response.json();
      setSuccessMessage(
        `Generated simulated reading #${data.reading.id}: Moisture ${data.reading.soil_moisture_pct}%, Temp ${data.reading.temperature_c}°C, Humidity ${data.reading.humidity_pct}%.`
      );

      // Refresh both the latest reading and history table immediately
      await fetchSensorData();
    } catch (err) {
      setErrorMessage(err.message || 'Failed to generate simulated reading.');
    } finally {
      setIsGenerating(false);
    }
  };

  return (
    <div className="page-container">
      {/* Simulation Disclaimer Banner */}
      <div className="sim-banner">
        <div className="sim-banner-icon">
          <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
            <circle cx="12" cy="12" r="10" />
            <line x1="12" y1="8" x2="12" y2="12" />
            <line x1="12" y1="16" x2="12.01" y2="16" />
          </svg>
        </div>
        <div>
          <div className="sim-banner-title">Simulation Environment (OS PBL)</div>
          <div className="sim-banner-text">
            All telemetry metrics below are generated by algorithmic simulation within the FastAPI backend
            and stored into SQLite. No physical IoT hardware sensors are interfaced.
          </div>
        </div>
      </div>

      {/* Action Toolbar */}
      <div className="actions-toolbar">
        <div className="toolbar-info">
          <h3>Agricultural Telemetry Stream</h3>
          <p>
            Connected to <code>{apiBase}/api/sensors</code> • SQLite storage
          </p>
        </div>

        <div style={{ display: 'flex', gap: '0.75rem', alignItems: 'center' }}>
          <button
            type="button"
            className="btn-retry"
            onClick={fetchSensorData}
            disabled={isLoading || isGenerating}
            title="Refresh sensor records"
          >
            <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round">
              <path d="M21.5 2v6h-6M21.34 15.57a10 10 0 1 1-.57-8.38l5.67-5.67" />
            </svg>
            <span>{isLoading ? 'Refreshing...' : 'Refresh'}</span>
          </button>

          <button
            type="button"
            className="btn-generate"
            onClick={handleGenerateReading}
            disabled={isGenerating || isLoading}
          >
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
              <line x1="12" y1="5" x2="12" y2="19" />
              <line x1="5" y1="12" x2="19" y2="12" />
            </svg>
            <span>{isGenerating ? 'Simulating...' : 'Generate Simulated Reading'}</span>
          </button>
        </div>
      </div>

      {/* Success / Error Feedback Alerts */}
      {successMessage && (
        <div className="feedback-alert success">
          <span>{successMessage}</span>
          <button
            type="button"
            onClick={() => setSuccessMessage(null)}
            style={{ background: 'none', border: 'none', cursor: 'pointer', color: 'inherit' }}
          >
            ✕
          </button>
        </div>
      )}

      {errorMessage && (
        <div className="feedback-alert error">
          <span>{errorMessage}</span>
          <button
            type="button"
            onClick={() => setErrorMessage(null)}
            style={{ background: 'none', border: 'none', cursor: 'pointer', color: 'inherit' }}
          >
            ✕
          </button>
        </div>
      )}

      {/* Latest Metrics Cards */}
      <h3 className="section-heading">Latest Telemetry Readings</h3>
      <div className="metric-cards-grid">
        {/* Metric 1: Soil Moisture */}
        <div className="metric-card">
          <div className="metric-card-header">
            <span className="metric-title">Soil Moisture</span>
            <div className="metric-icon-box icon-moisture">
              <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                <path d="M12 2.69l5.66 5.66a8 8 0 1 1-11.31 0z" />
              </svg>
            </div>
          </div>
          <div className="metric-value-display">
            <span className="metric-num">
              {latestReading ? latestReading.soil_moisture_pct : '--'}
            </span>
            <span className="metric-unit">%</span>
          </div>
          <div className="metric-timestamp">
            {latestReading ? `Recorded: ${formatTimestamp(latestReading.recorded_at)}` : 'Awaiting data'}
          </div>
        </div>

        {/* Metric 2: Ambient Temperature */}
        <div className="metric-card">
          <div className="metric-card-header">
            <span className="metric-title">Temperature</span>
            <div className="metric-icon-box icon-temp">
              <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                <path d="M14 14.76V3.5a2.5 2.5 0 0 0-5 0v11.26a4.5 4.5 0 1 0 5 0z" />
              </svg>
            </div>
          </div>
          <div className="metric-value-display">
            <span className="metric-num">
              {latestReading ? latestReading.temperature_c : '--'}
            </span>
            <span className="metric-unit">°C</span>
          </div>
          <div className="metric-timestamp">
            {latestReading ? `Recorded: ${formatTimestamp(latestReading.recorded_at)}` : 'Awaiting data'}
          </div>
        </div>

        {/* Metric 3: Air Humidity */}
        <div className="metric-card">
          <div className="metric-card-header">
            <span className="metric-title">Air Humidity</span>
            <div className="metric-icon-box icon-humidity">
              <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                <path d="M17.5 19H9a7 7 0 1 1 6.71-9h1.79a4.5 4.5 0 1 1 0 9Z" />
              </svg>
            </div>
          </div>
          <div className="metric-value-display">
            <span className="metric-num">
              {latestReading ? latestReading.humidity_pct : '--'}
            </span>
            <span className="metric-unit">%</span>
          </div>
          <div className="metric-timestamp">
            {latestReading ? `Recorded: ${formatTimestamp(latestReading.recorded_at)}` : 'Awaiting data'}
          </div>
        </div>
      </div>

      {/* Historical Readings Table */}
      <div className="data-table-card">
        <div className="data-table-header">
          <h3>Sensor Readings History</h3>
          <span className="sidebar-footer-badge">
            {historyReadings.length} {historyReadings.length === 1 ? 'Record' : 'Records'}
          </span>
        </div>

        {historyReadings.length === 0 ? (
          <div className="empty-readings-box">
            <div className="empty-readings-icon">
              <svg width="26" height="26" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                <rect x="2" y="7" width="20" height="14" rx="2" ry="2" />
                <path d="M16 21V5a2 2 0 0 0-2-2h-4a2 2 0 0 0-2 2v16" />
              </svg>
            </div>
            <h4>No Sensor Readings Yet</h4>
            <p>
              The SQLite database table is currently empty. Click the{' '}
              <strong>"Generate Simulated Reading"</strong> button above to persist your first agricultural data point.
            </p>
          </div>
        ) : (
          <div className="data-table-container">
            <table className="custom-table">
              <thead>
                <tr>
                  <th>ID</th>
                  <th>Recorded At</th>
                  <th>Soil Moisture</th>
                  <th>Temperature</th>
                  <th>Humidity</th>
                  <th>Source</th>
                </tr>
              </thead>
              <tbody>
                {historyReadings.map((reading) => (
                  <tr key={reading.id}>
                    <td>
                      <strong>#{reading.id}</strong>
                    </td>
                    <td>{formatTimestamp(reading.recorded_at)}</td>
                    <td>
                      <span style={{ fontWeight: 600, color: 'var(--primary-dark)' }}>
                        {reading.soil_moisture_pct}%
                      </span>
                    </td>
                    <td>{reading.temperature_c} °C</td>
                    <td>{reading.humidity_pct} %</td>
                    <td>
                      <span className="badge-source">{reading.source}</span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}
